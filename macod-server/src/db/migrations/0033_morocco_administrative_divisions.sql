-- Morocco administrative divisions + currency swap (DZD → MAD).
-- (MaCod Phase 1: D1 schema migration.)
--
-- Adds two additive tables (morocco_regions, morocco_provinces) seeded from
-- cod-shared/lib/morocco-cities.ts, and migrates every existing store's
-- currency default from Algerian Dinar (DZD, "دج") to Moroccan Dirham
-- (MAD, "د.م.").
--
-- Coexistence with wilayas: the Algeria tables (wilayas, communes,
-- carrier_wilayas) are NOT touched. During the migration window both
-- country datasets live side-by-side; the storefront chooses which to
-- render based on stores.currency. Once the Morocco rollout is complete
-- and no store reads wilayas, a follow-up migration can drop them.
--
-- Rollback for the currency swap:
--   UPDATE stores SET currency = 'DZD', currency_symbol = 'دج' WHERE currency = 'MAD';
-- Rollback for the new tables:
--   DROP TABLE morocco_provinces;
--   DROP TABLE morocco_regions;
-- The seed INSERTs are `INSERT OR IGNORE`, so re-running the migration is safe.

-- ── Regions (12) ──────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS morocco_regions (
  id TEXT PRIMARY KEY,
  name_fr TEXT NOT NULL,
  name_ar TEXT NOT NULL
);

-- ── Provinces & prefectures (72) ───────────────────────────────────────────
CREATE TABLE IF NOT EXISTS morocco_provinces (
  id        TEXT PRIMARY KEY,
  name_fr   TEXT NOT NULL,
  name_ar   TEXT NOT NULL,
  region_id TEXT NOT NULL REFERENCES morocco_regions(id),
  hub_code  TEXT NOT NULL  -- IATA-style 3-letter code used by Cathedis/DHL Maroc labels
);

CREATE INDEX IF NOT EXISTS idx_morocco_provinces_region ON morocco_provinces(region_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_morocco_provinces_hub_code ON morocco_provinces(hub_code);

-- ── Currency swap on stores ────────────────────────────────────────────────
-- Existing stores that were provisioned under the Algeria default carry
-- currency='DZD' / currency_symbol='دج'. Flip them to the Moroccan defaults
-- so the storefront renders "د.م." from the first request after migration.
UPDATE stores
   SET currency = 'MAD',
       currency_symbol = 'د.م.'
 WHERE currency = 'DZD';

